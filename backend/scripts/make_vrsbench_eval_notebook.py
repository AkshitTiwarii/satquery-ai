"""Build a Kaggle kernel that scores VRSBench with and without the zoom step - trains nothing.

    python scripts/make_vrsbench_eval_notebook.py [--user ichigooo0o] [--limit 400] [--adapter-kernel USER/SLUG]

Why a kernel and not the box: measuring is the bottleneck. The office card is scoring a
full split for ten hours; this puts the zoom question on a T4 instead and answers it in
about an hour. And it is the VRSBench scoring path RAO's task 3 needs anyway.

What it runs, on the SAME stratified rows, fp16: referring base, referring base + zoom, VQA
base, VQA base + zoom. The zoom gain is the pair difference inside one kernel, so precision
and rows cancel. (nf4 on the 4060 remains the number for a slide; this is the decision.)
With --adapter-kernel, the mounted adapter is scored the same two ways as well.

The satquery package and the harness are EMBEDDED, so the kernel scores the engine's own
zoom functions and the number measures the engine, not a copy.
"""
import argparse
import base64
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EMBED_SCRIPTS = ["scripts/eval_vrsbench.py", "scripts/eval_ground.py", "scripts/qwen_loader.py",
                 "scripts/get_vrsbench.py"]


def code(*lines):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": list(lines)}


def md(*lines):
    return {"cell_type": "markdown", "metadata": {}, "source": list(lines)}


def payload():
    files = {}
    rels = list(EMBED_SCRIPTS)
    rels += [os.path.relpath(p, ROOT).replace(os.sep, "/")
             for p in glob.glob(os.path.join(ROOT, "satquery", "*.py"))]
    rels += [os.path.relpath(p, ROOT).replace(os.sep, "/")
             for p in glob.glob(os.path.join(ROOT, "satquery", "*.json"))]
    rels += [os.path.relpath(p, ROOT).replace(os.sep, "/")
             for p in glob.glob(os.path.join(ROOT, "satquery", "schemas", "*.json"))]
    for rel in rels:
        with open(os.path.join(ROOT, rel), "rb") as fh:
            files[rel] = base64.b64encode(fh.read()).decode()
    assert "satquery/zoom.py" in files and "scripts/eval_vrsbench.py" in files
    return json.dumps(files), rels


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", default="ichigooo0o")
    ap.add_argument("--slug", default="satquery-vrsbench-zoom")
    ap.add_argument("--limit", type=int, default=400)
    ap.add_argument("--adapter-kernel", default=None, metavar="USER/SLUG",
                    help="also score this kernel's lora_adapter, with and without zoom")
    a = ap.parse_args()
    pl, rels = payload()

    def run_cell(task, adapter, zoom, out):
        flags = " --zoom" if zoom else ""
        ad = " --adapter /kaggle/working/adapter" if adapter else ""
        return ("!cd /kaggle/working/src && python scripts/eval_vrsbench.py --task %s --limit %d --dtype fp16 "
                "--max-pixels 256 --model Qwen/Qwen2.5-VL-3B-Instruct --ann-dir /kaggle/working/data/vrsbench "
                "--images /kaggle/working/data/vrsbench/Images_val.zip%s%s --out /kaggle/working/%s\n"
                % (task, a.limit, ad, flags, out))

    runs = [("refer", False, False, "vrs_refer_base"), ("refer", False, True, "vrs_refer_base_zoom"),
            ("vqa", False, False, "vrs_vqa_base"), ("vqa", False, True, "vrs_vqa_base_zoom")]
    if a.adapter_kernel:
        runs += [("refer", True, False, "vrs_refer_adapter"), ("refer", True, True, "vrs_refer_adapter_zoom"),
                 ("vqa", True, False, "vrs_vqa_adapter"), ("vqa", True, True, "vrs_vqa_adapter_zoom")]

    cells = [
        md("# VRSBench: zoom-and-re-ask, with and without, same rows, one kernel\n",
           "Generated by `scripts/make_vrsbench_eval_notebook.py`. Trains nothing. Do not edit; regenerate.\n"),
        code(
            "# ---- 1. preflight ----\n",
            "import os\n",
            "os.environ['CUDA_VISIBLE_DEVICES'] = '0'\n",
            "import time, torch\n",
            "T_START = time.time()\n",
            "assert torch.cuda.is_available(), 'no GPU - set Accelerator in Settings'\n",
            "cap = torch.cuda.get_device_capability(0)\n",
            "print('card:', torch.cuda.get_device_name(0), '| capability', cap)\n",
            "assert cap >= (7, 0), 'landed on a %s (sm_%d%d) - set Accelerator to GPU T4 x2 and rerun' % (\n",
            "    torch.cuda.get_device_name(0), cap[0], cap[1])\n",
        ),
        code(
            "# ---- 2. deps + the embedded engine and harness ----\n",
            "!pip install -q 'transformers>=4.49,<5' -U torchao accelerate peft jsonschema\n",
            "import base64, json, os\n",
            "PAYLOAD = '''%s'''\n" % pl,
            "for rel, b64 in json.loads(PAYLOAD).items():\n",
            "    p = os.path.join('/kaggle/working/src', rel)\n",
            "    os.makedirs(os.path.dirname(p), exist_ok=True)\n",
            "    with open(p, 'wb') as fh:\n",
            "        fh.write(base64.b64decode(b64))\n",
            "print('wrote', len(json.loads(PAYLOAD)), 'files; zoom.py present:', os.path.exists('/kaggle/working/src/satquery/zoom.py'))\n",
            "import transformers, peft; print('transformers', transformers.__version__, '| peft', peft.__version__)\n",
        ),
        code(
            "# ---- 3. data: VRSBench val from the authors' HF repo (4 GB, resumable) ----\n",
            "!cd /kaggle/working/src && python scripts/get_vrsbench.py --dest /kaggle/working/data/vrsbench\n",
            "import os\n",
            "for f in ['VRSBench_EVAL_vqa.json', 'VRSBench_EVAL_referring.json', 'Images_val.zip']:\n",
            "    p = '/kaggle/working/data/vrsbench/' + f\n",
            "    assert os.path.exists(p), f\n",
            "    print('%-32s %12d bytes' % (f, os.path.getsize(p)))\n",
            "print('data ready %.1f min in' % ((time.time() - T_START) / 60))\n",
        ),
    ]
    if a.adapter_kernel:
        cells.append(code(
            "# ---- 3b. the adapter, mounted from %s ----\n" % a.adapter_kernel,
            "import glob, shutil\n",
            "cands = sorted(glob.glob('/kaggle/input/*/lora_adapter'))\n",
            "assert cands, 'no lora_adapter under /kaggle/input - add the kernel as an Input'\n",
            "shutil.copytree(cands[0], '/kaggle/working/adapter', dirs_exist_ok=True)\n",
            "print('adapter from', cands[0])\n",
        ))
    for task, adapter, zoom, out in runs:
        cells.append(code(
            "# ---- %s %s%s ----\n" % (task, "adapter" if adapter else "base", " + ZOOM" if zoom else ""),
            run_cell(task, adapter, zoom, out),
            "print('%.1f min in' % ((time.time() - T_START) / 60))\n",
        ))
    cells.append(code(
        "# ---- the table ----\n",
        "import json\n",
        "def num(name):\n",
        "    r = json.load(open('/kaggle/working/%s.json' % name))\n",
        "    if r['task'] == 'vqa':\n",
        "        return r['overall']['accuracy'] if 'overall' in r else r.get('overall_accuracy')\n",
        "    return r['overall']['acc50'] if 'overall' in r else r.get('acc50')\n",
        # repr, not json.dumps: this is Python source and JSON's false is a NameError in a cell
        "rows = %s\n" % repr([(t, ad, z, o) for t, ad, z, o in runs]),
        "print('%-8s %-8s %-6s %8s' % ('task', 'weights', 'zoom', 'score'))\n",
        "for t, ad, z, o in rows:\n",
        "    try:\n",
        "        s = num(o)\n",
        "    except Exception as e:\n",
        "        s = 'ERR %s' % e\n",
        "    print('%-8s %-8s %-6s %8s' % (t, 'adapter' if ad else 'base', 'yes' if z else 'no', s))\n",
        "print('total %.1f min' % ((time.time() - T_START) / 60))\n",
    ))
    nb = {"cells": cells, "nbformat": 4, "nbformat_minor": 5,
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                       "language_info": {"name": "python", "version": "3.10"},
                       "kaggle": {"accelerator": "nvidiaTeslaT4", "isInternetEnabled": True, "language": "python",
                                  "sourceType": "notebook", "isGpuEnabled": True}}}
    out = os.path.join(ROOT, "train", "vrsbench-zoom")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "vrsbench-zoom-kaggle.ipynb"), "w", encoding="utf-8") as fh:
        json.dump(nb, fh, indent=1)
    meta = {"id": "%s/%s" % (a.user, a.slug), "title": a.slug, "code_file": "vrsbench-zoom-kaggle.ipynb",
            "language": "python", "kernel_type": "notebook", "is_private": True, "enable_gpu": True,
            "enable_internet": True, "dataset_sources": [],
            "kernel_sources": [a.adapter_kernel] if a.adapter_kernel else [], "competition_sources": []}
    with open(os.path.join(out, "kernel-metadata.json"), "w", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=2)
    print("wrote", out, "->", meta["id"], "| runs", len(runs), "| embedded", len(rels), "files")


if __name__ == "__main__":
    main()
